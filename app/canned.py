"""정해 둔 문장을 글자 그대로 답해야 하는 질문.

곽봇(AI)은 persona.md 의 설정을 자기 말투로 다시 말한다 — "박...." 을 "박 …" 으로, 따옴표 모양을
바꾸고, 반말을 존댓말로 고친다. 탄생 이야기는 글자 그대로 나와야 해서, 흔한 물음은 AI 에게 보내지
않고 여기서 바로 답한다. 여기서 못 잡은 물음은 persona.md 의 "그대로 말하라" 지시로 최대한 맞춘다.

- 대상: 누가·어떻게 만들었냐 / 어떻게 태어났냐 / 무슨 기술·도구·모델로 만들었냐
- 학교 질문("이 건물 누가 지었어?", "졸업작품 무슨 툴로 만들어?")을 잘못 잡지 않도록,
  곽봇을 가리키는 말(너·곽봇 …)이 있거나 질문 전체가 짧은 경우에만 잡는다.
"""
from __future__ import annotations

import re

BIRTH = "창조주 박.... 님의 손짓 한 방에 만들어졌어요."

# 곽봇을 가리키는 말. '너무' 같은 단어에 걸리지 않게 낱말 경계를 본다
_YOU = re.compile(r"곽봇|(?:^|[\s,])(?:너|넌|널|너는|너를|너도|니가|네가|니|당신|챗봇|이\s*챗봇|이\s*봇)(?=$|[\s?!.,~])")

# 띄어쓰기를 지운 문장에서 찾는다
_MADE = re.compile(r"(누가|누구).{0,6}(만들|만듦|만든|개발|제작|창조|키웠|낳)"
                   r"|(만든|개발한|제작한|창조한)(사람|이|분|놈|애)"
                   r"|제작자|개발자|창조주|만든이|주인(이|은)?누구"
                   r"|(어떻게|어디서|언제).{0,4}(태어|생겨|만들어졌|탄생)"
                   r"|탄생(비화|이야기|스토리)|엄마누구|아빠누구|부모(가|님)?누구")
_TOOLS = re.compile(r"(무슨|어떤|뭘로|뭐로|무엇으로|어떻게).{0,8}"
                    r"(기술|언어|모델|도구|툴|ai|llm|프레임워크|스택|api|라이브러리|엔진|서버|코드|프로그램)"
                    r"|(뭘로|뭐로|무엇으로)(만들|만듦|개발|제작)|기술스택|사용(한|된)기술|(gpt|지피티|chatgpt|챗gpt|claude|클로드|라마|llama|groq|그록|제미나이|gemini)"
                    r"(야|임|이야|니|냐|써|씀|기반|로만|로만들)")


def reply(text: str) -> str | None:
    """정해 둔 답이 있으면 그 문장, 없으면 None (평소처럼 AI 가 답한다)."""
    t = text.strip().lower()
    if not t or len(t) > 60:
        return None
    flat = re.sub(r"[\s?!.,~\"'“”‘’]+", "", t)
    about_me = bool(_YOU.search(" " + t))
    short = len(flat) <= 9           # "누가 만들었어?", "무슨 모델 써?" 처럼 대상 없이 짧은 물음
    if (_MADE.search(flat) or _TOOLS.search(flat)) and (about_me or short):
        return BIRTH
    return None
